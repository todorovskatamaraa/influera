  <script>

    const passwordModal      = document.getElementById('password-modal');
    const passwordBackdrop   = document.getElementById('password-modal-backdrop');
    const btnOpenPassword    = document.getElementById('btn-open-password-modal');
    const btnClosePassword   = document.getElementById('password-modal-close');
    const btnCancelPassword  = document.getElementById('password-modal-cancel');

    function openPasswordModal() {
        if (!passwordModal) return;
        passwordModal.classList.remove('hidden');
    }

    function closePasswordModal() {
        if (!passwordModal) return;
        passwordModal.classList.add('hidden');
    }

    if (btnOpenPassword) {
        btnOpenPassword.addEventListener('click', openPasswordModal);
    }
    if (btnClosePassword) {
        btnClosePassword.addEventListener('click', closePasswordModal);
    }
    if (btnCancelPassword) {
        btnCancelPassword.addEventListener('click', closePasswordModal);
    }
    if (passwordBackdrop) {
        passwordBackdrop.addEventListener('click', closePasswordModal);
    }

    const passwordAlert      = document.getElementById('password-alert');
    const passwordAlertClose = document.getElementById('password-alert-close');

    if (passwordAlert && passwordAlertClose) {
        passwordAlertClose.addEventListener('click', () => {
            passwordAlert.classList.add('hidden');
        });
    }
  </script>
